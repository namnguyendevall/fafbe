-- FINAL REPAIR: ADDING MISSING 'id' COLUMNS AND RESTORING IDENTITIES
-- This script fixes tables like 'wallets' which use 'user_id' as PK but the code expects an 'id' column.

DO $$ 
DECLARE
    target_tables TEXT[] := ARRAY[
        'users', 'user_profiles', 'wallets', 'transactions', 'jobs', 
        'checkpoints', 'contracts', 'proposals', 'categories', 'skills', 
        'user_skills', 'job_skills', 'conversations', 'conversation_participants', 
        'messages', 'notifications', 'reviews', 'review_skill_ratings', 
        'posts', 'post_likes', 'post_comments', 'user_followers', 
        'otps', 'withdrawal_requests', 'work_sessions'
    ];
    t TEXT;
    max_id BIGINT;
BEGIN
    -- 1. SPECIFIC FIX FOR TABLES MISSING 'id' COLUMN
    FOREACH t IN ARRAY target_tables
    LOOP
        IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = t) THEN
            IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = t AND column_name = 'id') THEN
                BEGIN
                    EXECUTE format('ALTER TABLE %I ADD COLUMN id INTEGER', t);
                    -- Use a sequential number or another unique column to fill it
                    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = t AND column_name = 'user_id') THEN
                        EXECUTE format('UPDATE %I SET id = user_id', t);
                    ELSE
                        EXECUTE format('UPDATE %I SET id = row_number() OVER ()', t);
                    END IF;
                    RAISE NOTICE 'Added id column to table: %', t;
                EXCEPTION WHEN OTHERS THEN
                    RAISE NOTICE 'Could not add id column to table: % (Error: %)', t, SQLERRM;
                END;
            END IF;
        END IF;
    END LOOP;

    -- 2. ENSURE ALL 'id' COLUMNS HAVE IDENTITY AND SYNCED SEQUENCES
    FOREACH t IN ARRAY target_tables
    LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = t AND column_name = 'id') THEN
            BEGIN
                -- Fill any NULLs that might have appeared
                EXECUTE format('
                    WITH null_ids AS (
                        SELECT ctid, row_number() OVER () + COALESCE((SELECT max(id) FROM %I), 0) as new_id
                        FROM %I
                        WHERE id IS NULL
                    )
                    UPDATE %I t
                    SET id = n.new_id
                    FROM null_ids n
                    WHERE t.ctid = n.ctid', t, t, t);

                -- Set NOT NULL
                EXECUTE format('ALTER TABLE %I ALTER COLUMN id SET NOT NULL', t);

                -- Restore Identity property if missing
                IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = t AND column_name = 'id' AND is_identity = 'YES') THEN
                    EXECUTE format('ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', t);
                END IF;
                
                -- Sync sequence
                EXECUTE format('SELECT max(id) FROM %I', t) INTO max_id;
                IF max_id IS NOT NULL THEN
                    EXECUTE format('ALTER TABLE %I ALTER COLUMN id RESTART WITH %s', t, max_id + 1);
                END IF;
            EXCEPTION WHEN OTHERS THEN
                RAISE NOTICE 'Database repair failed for table: % (Error: %)', t, SQLERRM;
            END;
        END IF;
    END LOOP;
END $$;
