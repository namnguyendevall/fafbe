-- DATA REPAIR AND IDENTITY RESTORATION SCRIPT
-- This script fixes tables where ID columns might be NULL or sequences are out of sync.

DO $$ 
DECLARE
    target_tables TEXT[] := ARRAY[
        'users', 'user_profiles', 'wallets', 'transactions', 'jobs', 
        'checkpoints', 'contracts', 'proposals', 'categories', 'skills', 
        'user_skills', 'job_skills', 'conversations', 'conversation_participants', 
        'messages', 'notifications', 'reviews', 'review_skill_ratings', 
        'posts', 'post_likes', 'post_comments', 'user_followers', 
        'otps', 'withdrawal_requests', 'work_sessions'
    ];
    t TEXT;
    max_id BIGINT;
BEGIN
    FOREACH t IN ARRAY target_tables
    LOOP
        -- 1. Ensure table and id column exist
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = t AND column_name = 'id') THEN
            
            -- 2. Fill NULL IDs if any exist (extremely rare but possible given the error)
            -- We'll use a temporary sequence or row_number if needed
            BEGIN
                EXECUTE format('
                    WITH null_ids AS (
                        SELECT ctid, row_number() OVER () + COALESCE((SELECT max(id) FROM %I), 0) as new_id
                        FROM %I
                        WHERE id IS NULL
                    )
                    UPDATE %I t
                    SET id = n.new_id
                    FROM null_ids n
                    WHERE t.ctid = n.ctid', t, t, t);
            EXCEPTION WHEN OTHERS THEN
                RAISE NOTICE 'Could not fill null IDs for table: % (Error: %)', t, SQLERRM;
            END;

            -- 3. Ensure the column is NOT NULL
            BEGIN
                EXECUTE format('ALTER TABLE %I ALTER COLUMN id SET NOT NULL', t);
            EXCEPTION WHEN OTHERS THEN
                RAISE NOTICE 'Could not set NOT NULL for table: % (Error: %)', t, SQLERRM;
            END;

            -- 4. Try to add PRIMARY KEY if not exists
            IF NOT EXISTS (
                SELECT 1 FROM information_schema.table_constraints tc 
                JOIN information_schema.constraint_column_usage as ccu USING (constraint_name, table_schema)
                WHERE tc.constraint_type = 'PRIMARY KEY' AND tc.table_name = t AND ccu.column_name = 'id'
            ) THEN
                BEGIN
                    EXECUTE format('ALTER TABLE %I ADD PRIMARY KEY (id)', t);
                    RAISE NOTICE 'Added PRIMARY KEY to table: %', t;
                EXCEPTION WHEN OTHERS THEN
                    RAISE NOTICE 'Could not add PRIMARY KEY to table: % (Error: %)', t, SQLERRM;
                END;
            END IF;

            -- 5. Add IDENTITY property
            IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = t AND column_name = 'id' AND is_identity = 'YES') THEN
                BEGIN
                    EXECUTE format('ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', t);
                    RAISE NOTICE 'Added identity to table: %', t;
                EXCEPTION WHEN OTHERS THEN
                    -- If it already has a default value (like a serial), we might need to do something else
                    RAISE NOTICE 'Could not add identity to table: % (Error: %)', t, SQLERRM;
                END;
            END IF;
            
            -- 6. Sync identity sequence
            BEGIN
                EXECUTE format('SELECT max(id) FROM %I', t) INTO max_id;
                IF max_id IS NOT NULL THEN
                    EXECUTE format('ALTER TABLE %I ALTER COLUMN id RESTART WITH %s', t, max_id + 1);
                    RAISE NOTICE 'Restarted sequence for table: % at %', t, max_id + 1;
                END IF;
            EXCEPTION WHEN OTHERS THEN
                RAISE NOTICE 'Could not restart sequence for table: % (Error: %)', t, SQLERRM;
            END;

        END IF;
    END LOOP;
END $$;
