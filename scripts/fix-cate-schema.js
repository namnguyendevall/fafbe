const dotenv = require('dotenv');
dotenv.config();
const pool = require('../src/config/database');

async function fixSchema() {
  try {
    console.log('--- Repairing category_proposals and job_categories identity columns ---');
    
    // 1. Fix category_proposals
    await pool.query(`
      DO $$ BEGIN
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='category_proposals' AND column_name='id') THEN
            IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='category_proposals' AND column_name='id' AND is_identity='YES') THEN
                ALTER TABLE category_proposals ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            END IF;
        END IF;
      END $$;
    `);
    console.log('1. Fixed category_proposals.id identity');

    // 2. Fix job_categories
    await pool.query(`
      DO $$ BEGIN
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='job_categories' AND column_name='id') THEN
            IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='job_categories' AND column_name='id' AND is_identity='YES') THEN
                ALTER TABLE job_categories ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            END IF;
        END IF;
      END $$;
    `);
    console.log('2. Fixed job_categories.id identity');

    console.log('✅ Schema repair SUCCESS!');
    process.exit(0);
  } catch (err) {
    console.error('ERROR during repair:', err.message);
    process.exit(1);
  }
}

fixSchema();
