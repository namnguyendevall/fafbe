const dotenv = require('dotenv');
dotenv.config();
const pool = require('../src/config/database');

async function fixWorkflowSchema() {
  try {
    console.log('--- Repairing Workflow Tables Schema ---');
    
    // 1. Fix disputes identity
    await pool.query(`
      DO $$ BEGIN
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='disputes' AND column_name='id') THEN
            IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='disputes' AND column_name='id' AND is_identity='YES') THEN
                ALTER TABLE disputes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            END IF;
        END IF;
      END $$;
    `);
    console.log('1. Fixed disputes.id identity');

    // 2. Fix proposals identity (Just in case)
    await pool.query(`
      DO $$ BEGIN
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='proposals' AND column_name='id') THEN
            IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='proposals' AND column_name='id' AND is_identity='YES') THEN
                ALTER TABLE proposals ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            END IF;
        END IF;
      END $$;
    `);
    console.log('2. Fixed proposals.id identity');

    // 3. Add rework columns to checkpoints
    await pool.query(`
      ALTER TABLE checkpoints 
      ADD COLUMN IF NOT EXISTS rework_count INTEGER DEFAULT 0,
      ADD COLUMN IF NOT EXISTS rework_limit INTEGER DEFAULT 3;
    `);
    console.log('3. Added rework_count and rework_limit to checkpoints');

    console.log('✅ Workflow Schema repair SUCCESS!');
    process.exit(0);
  } catch (err) {
    console.error('ERROR during repair:', err.message);
    process.exit(1);
  }
}

fixWorkflowSchema();
