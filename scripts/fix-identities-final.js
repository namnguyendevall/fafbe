const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '../.env') });
const pool = require('../src/config/database');

async function fix() {
  const client = await pool.connect();
  try {
    console.log("Starting DB Repair...");
    
    // 1. Fix dispute_messages.id
    console.log("Fixing dispute_messages identity...");
    await client.query(`
      DO $$ 
      BEGIN 
        IF NOT EXISTS (
          SELECT 1 FROM information_schema.columns 
          WHERE table_name = 'dispute_messages' AND column_name = 'id' AND is_identity = 'YES'
        ) THEN
          ALTER TABLE dispute_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
          PERFORM setval(pg_get_serial_sequence('dispute_messages', 'id'), COALESCE(MAX(id), 1), true) FROM dispute_messages;
        END IF;
      END $$;
    `);

    // 2. Sync other identities just in case
    const tables = ['proposals', 'disputes'];
    for (const table of tables) {
      console.log(`Syncing ${table} identity...`);
      await client.query(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE(MAX(id), 1), true) FROM ${table}`);
    }

    console.log("DB Repair Complete!");
  } catch (err) {
    console.error("Repair Failed:", err);
  } finally {
    client.release();
    await pool.end();
    process.exit(0);
  }
}

fix();
