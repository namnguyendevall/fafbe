const path = require('path');
const fs = require('fs');
require('dotenv').config({ path: path.join(__dirname, '../.env') });
const pool = require('../src/config/database');

const logFile = path.join(__dirname, '../repair.log');
fs.writeFileSync(logFile, `Starting ULTIMATE DB REPAIR at ${new Date().toISOString()}\n`);

function log(msg) {
  console.log(msg);
  fs.appendFileSync(logFile, msg + '\n');
}

async function ultimateFix() {
  const client = await pool.connect();
  try {
    log("Starting ULTIMATE DB REPAIR (Independent Commits)...");

    const tables = [
      'dispute_messages', 'disputes', 'proposals', 'category_proposals', 'job_categories', 
      'otps', 'messages', 'transactions', 'post_likes', 'admin_notifications', 
      'ai_match_cache', 'checkpoint_submissions', 'dispute_evidences', 'post_comments', 'posts'
    ];
    
    for (const table of tables) {
      try {
        log(`Processing table: ${table}`);
        
        // 1. Check if column 'id' exists
        const colCheck = await client.query(
          "SELECT column_name, data_type FROM information_schema.columns WHERE table_name = $1 AND column_name = 'id'",
          [table]
        );
        
        if (colCheck.rows.length === 0) {
          log(`Table ${table} has no 'id' column. Skipping.`);
          continue;
        }

        const dataType = colCheck.rows[0].data_type;

        // 2. Clear existing identity/default
        log(`- Clearing existing identity/default for ${table}.id`);
        try { await client.query(`ALTER TABLE ${table} ALTER COLUMN id DROP IDENTITY IF EXISTS`); } catch (e) {}
        try { await client.query(`ALTER TABLE ${table} ALTER COLUMN id SET DEFAULT NULL`); } catch (e) {}

        // 3. Add robust default
        if (dataType.includes('int')) {
          log(`- Adding IDENTITY to ${table}.id (${dataType})`);
          await client.query(`ALTER TABLE ${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
          
          // Sync sequence
          const maxRes = await client.query(`SELECT COALESCE(MAX(id), 0) + 1 as next_val FROM ${table}`);
          const nextVal = maxRes.rows[0].next_val;
          log(`- Syncing sequence for ${table} to ${nextVal}`);
          // For identity columns, use RESTART WITH
          await client.query(`ALTER TABLE ${table} ALTER COLUMN id RESTART WITH ${nextVal}`);
        } else if (dataType === 'uuid') {
          log(`- Ensuring UUID default for ${table}.id`);
          await client.query(`ALTER TABLE ${table} ALTER COLUMN id SET DEFAULT gen_random_uuid()`);
        }

        log(`Table ${table} fixed successfully.`);
      } catch (tableErr) {
        log(`Failed to process table ${table}: ${tableErr.message}`);
      }
    }

    log("ULTIMATE REPAIR ATTEMPT COMPLETE!");
  } catch (err) {
    log(`Global script error: ${err.message}`);
  } finally {
    client.release();
    await pool.end();
    process.exit(0);
  }
}

ultimateFix();
